"""Regenerate ``tests/golden/replay_pin.json``.

The pin records the event-log hash and final-state hash of a few fixed runs on the shipped
content. ``tests/integration/test_replay_logs.py`` compares every build against it, so a change
in rules behaviour, content or random-number use that was not meant to happen fails a test on
every platform.

The runs are played by the scripted heuristic player, so a change to that player's decisions
changes them too; ``POLICY_VERSION`` is recorded for that reason.

Run this only when such a change is intended (and bump RULES_VERSION, content_version or
POLICY_VERSION first):

    python tools/update_replay_pin.py
"""

from __future__ import annotations

import json
from pathlib import Path

from battle_dice import RNG_ALGORITHM, RULES_VERSION
from battle_dice.content.loader import load_content
from battle_dice.core import commands as cmd
from battle_dice.core.engine import Engine
from battle_dice.core.events import events_hash, state_hash
from battle_dice.sim.policies import POLICY_VERSION, HeuristicPolicy, play_run

RUNS = [
    {"seed": 1, "party": ["squire", "apprentice", "scout"]},
    {"seed": 2, "party": ["scout"]},
    {"seed": 3, "party": ["squire", "squire", "apprentice", "scout", "scout"]},
]
PIN_PATH = Path(__file__).resolve().parent.parent / "tests" / "golden" / "replay_pin.json"


def play(seed: int, party: list[str]) -> dict[str, object]:
    content = load_content()
    engine = Engine(content)
    members = [{"class_id": class_id, "row": content.class_def(class_id)["suggested_row"]} for class_id in party]
    result = engine.do(cmd.START_RUN, seed=seed, party=members)
    assert result.accepted, result.reason
    outcome = play_run(engine, HeuristicPolicy())
    return {
        "seed": seed,
        "party": party,
        "outcome": outcome,
        "commands": len(engine.command_log),
        "events": len(engine.events),
        "events_hash": events_hash(engine.events),
        "final_state_hash": state_hash(engine.state),
    }


def build() -> dict[str, object]:
    content = load_content()
    return {
        "note": "Generated by tools/update_replay_pin.py. Do not edit by hand.",
        "rules_version": RULES_VERSION,
        "content_version": content.content_version,
        "content_hash": content.content_hash,
        "rng_algorithm": RNG_ALGORITHM,
        "policy": "heuristic",
        "policy_version": POLICY_VERSION,
        "runs": [play(run["seed"], run["party"]) for run in RUNS],
    }


if __name__ == "__main__":
    PIN_PATH.write_text(json.dumps(build(), indent=2) + "\n", encoding="utf-8")
    print(f"wrote {PIN_PATH}")
